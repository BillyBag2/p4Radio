"""Generate a 24 kHz mono signed PCM asset; never modifies the input WAV."""
from pathlib import Path
import math
import wave
import struct

root = Path(__file__).resolve().parents[1]
with wave.open(str(root / "assets/sounds/data-24.wav"), "rb") as source:
    if source.getsampwidth() != 2 or source.getnchannels() != 1:
        raise ValueError("Expected 16-bit mono PCM input")
    rate = source.getframerate()
    samples = struct.unpack("<%dh" % source.getnframes(), source.readframes(source.getnframes()))
# Windowed-sinc low-pass resampling avoids aliasing when reducing the sample rate.
target = 24000
cutoff = min(1.0, target / rate) * 0.90
output = []
for i in range(round(len(samples) * target / rate)):
    position = i * rate / target
    total = weight = 0.0
    for j in range(max(0, int(position) - 32), min(len(samples), int(position) + 33)):
        x = position - j
        if abs(x) >= 33:
            continue
        z = math.pi * x * cutoff
        sinc = 1.0 if abs(z) < 1e-12 else math.sin(z) / z
        w = cutoff * sinc * (0.5 + 0.5 * math.cos(math.pi * x / 33))
        total += samples[j] * w
        weight += w
    output.append(max(-32768, min(32767, round(total / weight))))
# Gentle endpoint fades suppress discontinuities without normalizing the asset.
fade = min(48, len(output) // 2)
for i in range(fade):
    output[i] = round(output[i] * i / fade)
    output[-1-i] = round(output[-1-i] * i / fade)
lines = [", ".join(map(str, output[i:i+16])) for i in range(0, len(output), 16)]
(root / "main/data_sound_data.hpp").write_text(
    "// Generated by tools/convert_data_sound.py; 24 kHz mono signed 16-bit PCM.\n"
    "#pragma once\n#include <cstdint>\nnamespace p4radio {\n"
    "inline constexpr int16_t kDataSound[] = {\n    " + ",\n    ".join(lines) + "\n};\n}\n")
print(f"Generated {len(output)} samples, {len(output)*2} PCM bytes")
